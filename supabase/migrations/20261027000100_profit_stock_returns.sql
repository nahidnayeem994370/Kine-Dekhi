create table if not exists public.product_costs (
  product_id bigint primary key references public.products(id) on delete cascade,
  purchase_cost numeric(12,2) not null default 0 check (purchase_cost >= 0),
  updated_at timestamptz not null default now()
);
alter table public.product_costs enable row level security;
revoke all on public.product_costs from anon, authenticated;
grant select, insert, update, delete on public.product_costs to authenticated;
drop policy if exists "Admins manage product costs" on public.product_costs;
create policy "Admins manage product costs" on public.product_costs
  for all to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

alter table public.orders
  add column if not exists division_name text,
  add column if not exists discount_amount numeric(12,2) not null default 0 check (discount_amount >= 0),
  add column if not exists offer_name text,
  add column if not exists courier_cost numeric(12,2) not null default 0 check (courier_cost >= 0),
  add column if not exists returned_at timestamptz,
  add column if not exists return_status text not null default 'none'
    check (return_status in ('none','requested','partial','returned','cancelled')),
  add column if not exists profit_data_complete boolean not null default false;

alter table public.order_items
  add column if not exists unit_cost_snapshot numeric(12,2) check (unit_cost_snapshot is null or unit_cost_snapshot >= 0),
  add column if not exists discount_snapshot numeric(12,2) not null default 0 check (discount_snapshot >= 0),
  add column if not exists returned_quantity integer not null default 0 check (returned_quantity >= 0),
  add column if not exists return_condition text not null default 'none'
    check (return_condition in ('none','good','damaged'));

create table if not exists public.order_returns (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete restrict,
  order_item_id bigint not null references public.order_items(id) on delete restrict,
  quantity integer not null check (quantity > 0),
  item_condition text not null check (item_condition in ('good','damaged')),
  refund_amount numeric(12,2) not null default 0 check (refund_amount >= 0),
  restock_applied boolean not null default false,
  notes text,
  created_at timestamptz not null default now(),
  created_by uuid
);
alter table public.order_returns enable row level security;
revoke all on public.order_returns from anon, authenticated;
grant select, insert, update on public.order_returns to authenticated;
drop policy if exists "Admins manage order returns" on public.order_returns;
create policy "Admins manage order returns" on public.order_returns
  for all to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

