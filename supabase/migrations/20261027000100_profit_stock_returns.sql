create table if not exists public.product_costs (
  product_id bigint primary key references public.products(id) on delete cascade,
  purchase_cost numeric(12,2) not null default 0 check (purchase_cost >= 0),
  updated_at timestamptz not null default now()
);
alter table public.product_costs enable row level security;
revoke all on public.product_costs from anon, authenticated;
grant select, insert, update, delete on public.product_costs to authenticated;
drop policy if exists "Admins manage product costs" on public.product_costs;
create policy "Admins manage product costs" on public.product_costs
  for all to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

alter table public.orders
  add column if not exists division_name text,
  add column if not exists discount_amount numeric(12,2) not null default 0 check (discount_amount >= 0),
  add column if not exists offer_name text,
  add column if not exists courier_cost numeric(12,2) not null default 0 check (courier_cost >= 0),
  add column if not exists returned_at timestamptz,
  add column if not exists return_status text not null default 'none'
    check (return_status in ('none','requested','partial','returned','cancelled')),
  add column if not exists profit_data_complete boolean not null default false;

alter table public.order_items
  add column if not exists unit_cost_snapshot numeric(12,2) check (unit_cost_snapshot is null or unit_cost_snapshot >= 0),
  add column if not exists discount_snapshot numeric(12,2) not null default 0 check (discount_snapshot >= 0),
  add column if not exists returned_quantity integer not null default 0 check (returned_quantity >= 0),
  add column if not exists return_condition text not null default 'none'
    check (return_condition in ('none','good','damaged'));

create table if not exists public.order_returns (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete restrict,
  order_item_id bigint not null references public.order_items(id) on delete restrict,
  quantity integer not null check (quantity > 0),
  item_condition text not null check (item_condition in ('good','damaged')),
  refund_amount numeric(12,2) not null default 0 check (refund_amount >= 0),
  restock_applied boolean not null default false,
  notes text,
  created_at timestamptz not null default now(),
  created_by uuid
);
alter table public.order_returns enable row level security;
revoke all on public.order_returns from anon, authenticated;
grant select, insert, update on public.order_returns to authenticated;
drop policy if exists "Admins manage order returns" on public.order_returns;
create policy "Admins manage order returns" on public.order_returns
  for all to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

-- Do not backfill historical purchase costs: old profit is unknown unless the
-- shop owner supplies the real cost for those orders. Keep them flagged incomplete.


-- Record a return atomically; only admins can execute this privileged operation.
create or replace function public.record_order_return(
  p_order_item_id bigint,
  p_quantity integer,
  p_condition text,
  p_refund_amount numeric default 0,
  p_notes text default null
) returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_item public.order_items%rowtype;
  v_order public.orders%rowtype;
  v_return_id bigint;
begin
  if coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') <> 'admin' then
    raise exception 'Admin access required' using errcode = '42501';
  end if;
  if p_quantity is null or p_quantity < 1 then
    raise exception 'Return quantity must be positive';
  end if;
  if p_condition not in ('good','damaged') then
    raise exception 'Return condition must be good or damaged';
  end if;
  if coalesce(p_refund_amount,0) < 0 then
    raise exception 'Refund amount cannot be negative';
  end if;

  select * into v_item from public.order_items
    where id = p_order_item_id for update;
  if not found then raise exception 'Order item not found'; end if;
  select * into v_order from public.orders
    where id = v_item.order_id for update;
  if not found then raise exception 'Order not found'; end if;
  if v_order.order_status <> 'delivered' then
    raise exception 'Only delivered orders can be returned';
  end if;
  if v_item.is_gift then raise exception 'Gift items cannot be returned for refund';
  end if;
  if v_item.returned_quantity + p_quantity > v_item.quantity then
    raise exception 'Return quantity exceeds purchased quantity';
  end if;

  insert into public.order_returns
    (order_id, order_item_id, quantity, item_condition, refund_amount, restock_applied, notes, created_by)
  values
    (v_order.id, v_item.id, p_quantity, p_condition, coalesce(p_refund_amount,0),
     p_condition = 'good', nullif(trim(coalesce(p_notes,'')),''), auth.uid())
  returning id into v_return_id;

  update public.order_items
    set returned_quantity = returned_quantity + p_quantity,
        return_condition = case
          when returned_quantity + p_quantity >= quantity then p_condition
          when return_condition = 'damaged' or p_condition = 'damaged' then 'damaged'
          else 'good'
        end
    where id = v_item.id;

  if p_condition = 'good' and v_item.product_id is not null then
    update public.products
      set stock = stock + p_quantity, updated_at = now()
      where id = v_item.product_id;
  end if;

  update public.orders
    set return_status = case
          when exists (
            select 1 from public.order_items oi
            where oi.order_id = v_order.id
              and oi.returned_quantity < oi.quantity
              and not oi.is_gift
          ) then 'partial'
          else 'returned'
        end,
        returned_at = now()
    where id = v_order.id;

  return v_return_id;
end;
$$;
revoke all on function public.record_order_return(bigint, integer, text, numeric, text) from public, anon;
grant execute on function public.record_order_return(bigint, integer, text, numeric, text) to authenticated;
